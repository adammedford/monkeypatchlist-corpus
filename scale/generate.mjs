// Generates the scale fixture's app shells (apps/<variant>/index.js) and SDK modules (sdk/<app>.js) from one table.
//   node scale/generate.mjs
// Each SDK module is the corpus app's base config (../apps/<app>/index.js) without its `__corpusReady` line, so only
// the shell says when the page is ready. The shell loads every module through a dynamic import, one after another in a
// fixed order, so webpack splits them into chunks behind one chunk loader (one link group) and installs stay ordered.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCALE = resolve(fileURLToPath(import.meta.url), '..');
const CORPUS = resolve(SCALE, '..');
const READY = /^window\.__corpusReady = true;\n/m;

// Polyfills first, then zone.js (it checks that nothing replaces its Promise after it loads), then the rest by name.
const FIRST = ['core-js', 'es6-promise', 'promise-polyfill', 'whatwg-fetch', 'zonejs'];
const ALL = (await readdir(join(CORPUS, 'apps'), { withFileTypes: true })).filter((e) => e.isDirectory() && !e.name.startsWith('.')).map((e) => e.name);
const SDKS = [...FIRST, ...ALL.filter((a) => !FIRST.includes(a)).sort()];

// Filler: widely used libraries that are not corpus SDKs, pinned in package.json. They bring the variant up to size.
// Sizes are the minified webpack output; see the README table.
const VARIANTS = {
  '1mb': { sdks: ['core-js', 'zonejs', 'clarity', 'newrelic', 'segment', 'sentry-11'], filler: [] },
  '2.5mb': { sdks: SDKS, filler: ['react', 'react-dom/client', 'lodash'] },
  '5mb': { sdks: SDKS, filler: ['react', 'react-dom/client', 'lodash', 'rxjs', 'moment', 'd3', 'chart.js/auto', 'three', 'echarts'] },
};

const chunk = (s) => s.replace(/[^a-z0-9]+/gi, '-').replace(/-$/, '');

await rm(join(SCALE, 'sdk'), { recursive: true, force: true });
await mkdir(join(SCALE, 'sdk'), { recursive: true });
for (const app of SDKS) {
  const src = await readFile(join(CORPUS, 'apps', app, 'index.js'), 'utf8');
  if (!READY.test(src)) throw new Error(`${app}: no __corpusReady line`);
  await writeFile(join(SCALE, 'sdk', `${app}.js`), `// Generated by scale/generate.mjs from apps/${app}/index.js.\n${src.replace(READY, '')}`);
}

await rm(join(SCALE, 'apps'), { recursive: true, force: true });
for (const [name, v] of Object.entries(VARIANTS)) {
  const steps = [
    ...v.sdks.map((a) => `  () => import(/* webpackChunkName: "sdk-${a}" */ '../../sdk/${a}.js'),`),
    ...v.filler.map((l) => `  () => import(/* webpackChunkName: "lib-${chunk(l)}" */ '${l}'),`),
  ];
  const shell = `// Generated by scale/generate.mjs: the ${name} scale fixture.
const steps = [
${steps.join('\n')}
];
(async () => {
  for (const step of steps) {
    // One SDK that throws must not stop the rest; the error still reaches the harness as a page error.
    try { await step(); } catch (e) { setTimeout(() => { throw e; }); }
  }
  window.__corpusReady = true;
})();
`;
  await mkdir(join(SCALE, 'apps', name), { recursive: true });
  await writeFile(join(SCALE, 'apps', name, 'index.js'), shell);
}
console.log(`${SDKS.length} SDK modules, ${Object.keys(VARIANTS).length} variants`);
