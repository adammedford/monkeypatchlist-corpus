// Exercise-variant bookkeeping. Reads the base ground truth and the three variant ground truths and writes:
//   labels/derived-reachability.json  reachability labels derived from where each target was observed (the label-derivation rules).
//                                     Uses runtime ground truth only, never resolver output.
//   variants/report.json              per-(variant, app, run) bundler invariance, derived-vs-hand-label conflicts, and,
//                                     with --triage <full-triage.json>, which dormant resolver findings each variant confirms.
//   node scripts/variants.mjs [--triage ../prototypes/resolver/out/full-triage.json]
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HARNESS = resolve(fileURLToPath(import.meta.url), '../..');
const args = process.argv.slice(2);
const TRIAGE = args.includes('--triage') ? resolve(args[args.indexOf('--triage') + 1]) : null;
const lib = (app) => app.split('--')[0]; // core-js--members is a second core-js run
const json = async (f) => JSON.parse(await readFile(f, 'utf8'));

// Every ground-truth file of an npm build under dir: {bundler, app, variant, run, gt}.
async function load(dir) {
  const out = [];
  for (const b of (await readdir(dir, { withFileTypes: true }).catch(() => [])).filter((e) => e.isDirectory() && e.name !== 'static' && !e.name.startsWith('.')))
    for (const a of (await readdir(join(dir, b.name), { withFileTypes: true })).filter((e) => e.isDirectory() && !e.name.startsWith('.')))
      for (const f of (await readdir(join(dir, b.name, a.name))).filter((n) => n.endsWith('.json')).sort()) {
        const [variant, run = null] = f.replace(/\.json$/, '').split('.');
        out.push({ bundler: b.name, app: a.name, variant, run, gt: await json(join(dir, b.name, a.name, f)) });
      }
  return out;
}

const SOURCES = {
  base: join(HARNESS, 'ground-truth'),
  'features-on': join(HARNESS, 'variants/features-on/ground-truth'),
  'lazy-chunks': join(HARNESS, 'variants/lazy-chunks/ground-truth'),
  'native-absent': join(HARNESS, 'variants/native-absent/ground-truth'),
};
const runs = {};
for (const [k, dir] of Object.entries(SOURCES)) runs[k] = await load(dir);

// seen[library][target] = { base: bool, 'features-on': Set(app), 'lazy-chunks': Set(app), 'native-absent': Set(app.run), effects: {source: Set} }
const seen = {};
const invariance = [];
for (const [source, list] of Object.entries(runs)) {
  const groups = {};
  for (const r of list) {
    const L = lib(r.app);
    seen[L] ??= {};
    for (const m of r.gt.mutations) {
      const s = (seen[L][m.target] ??= { effects: {} });
      if (source === 'base') s.base = true;
      else (s[source] ??= new Set()).add(r.run ? `${r.app}.${r.run}` : r.app);
      (s.effects[source] ??= new Set()).add(m.effect);
    }
    const key = `${r.app}${r.run ? '.' + r.run : ''}`;
    (groups[key] ??= []).push({ build: `${r.bundler}/${r.variant}`, set: r.gt.mutations.map((m) => `${m.target}|${m.effect}`).sort().join('\n') });
  }
  if (source === 'base') continue;
  for (const [key, g] of Object.entries(groups)) {
    const distinct = [...new Set(g.map((x) => x.set))];
    invariance.push({ source, run: key, builds: g.length, identical: distinct.length === 1, ...(distinct.length > 1 ? { differing: g.filter((x) => x.set !== g[0].set).map((x) => x.build) } : {}) });
  }
}

// ---- derived labels (the label-derivation rules): base -> not guarded-native-absence; only native-absent -> guarded-native-absence;
// only features-on or lazy-chunks -> conditional; reached both by deleting a native and by config -> conditional.
const derived = {
  $schema: 'Reachability labels derived from the exercise variants by the label-derivation rules, separate from the hand labels in unobserved.json. Per library: `not-guarded-native-absence` lists targets observed in the base run (the base-run invariant; the unconditional/conditional split stays with the hand sample). `guarded-native-absence` lists targets observed only in the native-absent variant, `conditional` targets observed only with features on or lazy chunks loaded, or reached both ways (native-absent OR config is an OR, which the reachability rules make conditional). `observedIn` names the variant runs (app or app.run). Generated by scripts/variants.mjs from runtime ground truth only; applies to every bundler and maps variant of the app.',
};
for (const L of Object.keys(seen).sort()) {
  const out = { 'not-guarded-native-absence': [], 'guarded-native-absence': [], conditional: [] };
  for (const t of Object.keys(seen[L]).sort()) {
    const s = seen[L][t];
    if (s.base) { out['not-guarded-native-absence'].push(t); continue; }
    const na = [...(s['native-absent'] ?? [])].sort(), fo = [...(s['features-on'] ?? [])].map((a) => `features-on:${a}`), lc = [...(s['lazy-chunks'] ?? [])].map((a) => `lazy-chunks:${a}`);
    const effects = [...new Set(Object.values(s.effects).flatMap((e) => [...e]))].sort();
    const observedIn = [...na.map((r) => `native-absent:${r}`), ...fo, ...lc].sort();
    if (na.length && !fo.length && !lc.length) out['guarded-native-absence'].push({ target: t, effects, observedIn, ...(L === 'newrelic' ? { note: 'The native-absent run uses the lazy-chunks build: the guard is in the recorder chunk, which only loads with session_replay enabled.' } : {}) });
    else out.conditional.push({ target: t, effects, observedIn, basis: na.length ? 'native-absent and features-on/lazy-chunks' : 'features-on/lazy-chunks only' });
  }
  derived[L] = out;
}
await writeFile(join(HARNESS, 'labels/derived-reachability.json'), JSON.stringify(derived, null, 1) + '\n');

// ---- derived vs hand labels
const hand = await json(join(HARNESS, 'labels/unobserved.json'));
const conflicts = [];
for (const [L, entries] of Object.entries(hand)) {
  if (L === '$schema' || !derived[L]) continue;
  for (const e of entries) {
    const d = derived[L];
    const got = d['not-guarded-native-absence'].includes(e.target) ? 'not-guarded-native-absence'
      : d['guarded-native-absence'].some((x) => x.target === e.target) ? 'guarded-native-absence'
      : d.conditional.some((x) => x.target === e.target) ? 'conditional' : null;
    if (got && got !== e.reachability && !(got === 'not-guarded-native-absence' && e.reachability !== 'guarded-native-absence'))
      conflicts.push({ library: L, target: e.target, hand: e.reachability, derived: got, corrected: !!e.correction });
  }
}

// ---- dormant resolver findings (full-triage.json, class unobserved-real?) reached by each variant
let dormant = null;
if (TRIAGE) {
  const triage = await json(TRIAGE);
  dormant = { source: TRIAGE.replace(resolve(HARNESS, '..') + '/', ''), libraries: {}, totals: {} };
  // A runtime record matches a finding by target, or by the member it shadows (the rule for shadowing writes).
  const matchers = {};
  for (const [source, list] of Object.entries(runs))
    for (const r of list) for (const m of r.gt.mutations) {
      const L = lib(r.app);
      for (const name of [m.target, m.shadows].filter(Boolean)) ((matchers[L] ??= {})[name] ??= new Set()).add(source);
    }
  const T = { dormant: 0, 'features-on': 0, 'lazy-chunks': 0, 'native-absent': 0, anyVariant: 0, none: 0, base: 0 };
  for (const [L, v] of Object.entries(triage)) {
    const items = v.fp.filter((e) => e.cls === 'unobserved-real?');
    if (!items.length) continue;
    const rows = items.map((e) => ({ target: e.target, reach: e.reach, reachedBy: [...(matchers[L]?.[e.target] ?? [])].sort() }));
    const count = (k) => rows.filter((r) => r.reachedBy.includes(k)).length;
    const c = { dormant: rows.length, 'features-on': count('features-on'), 'lazy-chunks': count('lazy-chunks'), 'native-absent': count('native-absent'), base: count('base'),
      anyVariant: rows.filter((r) => r.reachedBy.some((k) => k !== 'base')).length };
    c.none = rows.length - rows.filter((r) => r.reachedBy.length).length;
    for (const k of Object.keys(T)) T[k] += c[k];
    dormant.libraries[L] = { counts: c, confirmed: rows.filter((r) => r.reachedBy.length), unreached: rows.filter((r) => !r.reachedBy.length).map((r) => r.target) };
  }
  dormant.totals = T;
}

await writeFile(join(HARNESS, 'variants/report.json'), JSON.stringify({ invariance, conflicts, ...(dormant ? { dormant } : {}) }, null, 1) + '\n');
console.log(`invariance: ${invariance.filter((x) => !x.identical).length} of ${invariance.length} (variant, app, run) groups differ across builds`);
for (const x of invariance.filter((x) => !x.identical)) console.log(`  ${x.source} ${x.run}: ${x.differing.join(', ')}`);
console.log(`derived: ${Object.entries(derived).filter(([k]) => k !== '$schema').map(([k, v]) => `${k} ${v['guarded-native-absence'].length} gna / ${v.conditional.length} cond / ${v['not-guarded-native-absence'].length} base`).join('; ')}`);
console.log(`conflicts with hand labels: ${conflicts.length}`);
for (const c of conflicts) console.log(`  ${c.library} ${c.target}: hand ${c.hand}${c.corrected ? ' (corrected)' : ''}, derived ${c.derived}`);
if (dormant) console.log('dormant:', JSON.stringify(dormant.totals));
